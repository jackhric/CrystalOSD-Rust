fn font_file() -> Option<Vec<u8>> {
    let folder =
        std::env::var_os("CRYSTALOSD_RESOURCES").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../Resources"));
    match std::fs::read(folder.join("FNTOSD")) {
        Ok(file) => Some(file),
        Err(_) => {
            eprintln!("skipped: no FNTOSD in {}", folder.display());
            None
        }
    }
}

struct Fixture {
    file: Vec<u8>,
    font: Font,
    traced: OutlineFont,
    heros: HerosFont,
    table: FitTable,
}

fn fixture() -> Option<Fixture> {
    let file = font_file()?;
    let font = Font::new(&file).unwrap();
    let traced = build(&font, font_hash(&file), &block_zero_codes(&font), 8);
    let heros = heros_for(&font);
    let table = FitTable::from_text(BUNDLED).unwrap();
    Some(Fixture { file, font, traced, heros, table })
}

#[test]
fn the_bundled_font_is_texgyre_heros_with_every_ascii_glyph() {
    assert!(HEROS_REGULAR.windows(20).any(|w| w == b"TeXGyreHeros-Regular"), "the CFF font's name");
    assert_eq!(HEROS_REGULAR.len(), 133_600, "texgyreheros-regular.otf 2.004, unmodified");
    let heros = HerosFont::regular(&(0x21..0x7f).collect::<Vec<_>>());
    assert_eq!(heros.units_per_em, 1000.0);
    assert_eq!(heros.glyphs.len(), 94);
    let zones = Zones::of(&heros);
    assert_eq!((zones.x_height, zones.cap_height), (524.0, 729.0));
    let o = &heros.glyphs[&('o' as i32)];
    assert!(o.contours.len() == 2 && glyph_enhance::trace::signed_area(&o.contours[0]) > 0.0);
}

#[test]
fn the_bundled_fit_is_this_fntosd_and_this_font() {
    let Some(f) = fixture() else { return };
    assert_eq!(f.table.fntosd, font_hash(&f.file));
    assert_eq!(f.table.heros, heros_hash());
    assert_eq!(f.table.glyphs.len(), block_zero_codes(&f.font).len());
    assert_eq!(FitTable::from_text(&f.table.to_text()).unwrap(), f.table, "the table reads back");
}

// The per-glyph fit and decision are deterministic (whatever the threads) and are what the bundled table holds: the table is
// regenerated by crystalosd-heros-fit --keep-runs from Resources/FNTOSD and fonts/texgyreheros-regular.otf alone.
#[test]
fn the_per_glyph_fit_is_deterministic_and_reproduces_the_bundled_table() {
    let Some(f) = fixture() else { return };
    let one = fit_glyphs(&f.font, &f.heros, &f.table.models, &f.traced, 1);
    let many = fit_glyphs(&f.font, &f.heros, &f.table.models, &f.traced, 7);
    assert_eq!(one, many);
    let fresh = FitTable { glyphs: one, ..f.table.clone() };
    assert_eq!(fresh.to_text(), f.table.to_text());
}

#[test]
fn every_heros_glyph_is_within_its_bound_and_margin_and_its_numbers_are_measured() {
    let Some(f) = fixture() else { return };
    let shapes = f.table.sharp_font(&f.font, &f.heros, &f.traced);
    for (code, e) in &f.table.glyphs {
        if e.choice != Choice::Heros {
            continue;
        }
        let (h, t) = (e.heros.unwrap(), e.traced.unwrap());
        assert!(h <= BOUND && h <= t + MARGIN, "{code:04x}: heros {h} traced {t}");
        let shape = &shapes.glyphs[code];
        assert_eq!(shape.source, Source::Heros);
        let measured = averaged_back(&f.font, *code, Some(shape), 4).unwrap().mean();
        assert!((measured - h).abs() < 2e-4, "{code:04x}: the table says {h}, the shape (placed to 4 decimals) measures {measured}");
    }
}

#[test]
fn glyphs_heros_does_not_draw_like_the_console_fall_back() {
    assert_eq!(decide(Some(0.05), Some(0.04)), Choice::Heros);
    assert_eq!(decide(Some(0.05 + MARGIN), Some(0.04)), Choice::Traced);
    assert_eq!(decide(Some(BOUND + 0.001), Some(0.2)), Choice::Traced);
    assert_eq!(decide(None, Some(0.04)), Choice::Traced);
    assert_eq!(decide(Some(0.05), None), Choice::Heros);
    assert_eq!(decide(None, None), Choice::Picture);
    let Some(f) = fixture() else { return };
    let choice = |c: i32| f.table.glyphs[&c].choice;
    for c in "#%@~".chars() {
        assert_eq!(choice(c as i32), Choice::Traced, "{c}: Sony redrew it");
    }
    for c in ('A'..='Z').chain('a'..='z').chain('0'..='9') {
        assert_eq!(choice(c as i32), Choice::Heros, "{c}");
    }
    for c in 0x410..0x450 {
        assert_eq!(choice(c), Choice::Traced, "Cyrillic {c:04x}: not in Heros");
    }
    for c in 0xd80d..=0xd810 {
        assert_eq!(choice(c), Choice::Picture, "{c:04x}: a grey plate, kept as its picture");
    }
    let shapes = f.table.sharp_font(&f.font, &f.heros, &f.traced);
    assert_eq!(shapes.glyphs[&('@' as i32)].source, Source::Traced);
    assert!(!shapes.glyphs.contains_key(&0xd80d));
}

// The console's metrics, not the font's, place the glyphs: Heros' ink stays inside each glyph's quad (originX + left - 1 to
// originX + right + 1), so the renderer's clamp never cuts it, and within the fitted reach of the console's own ink.
#[test]
fn heros_ink_stays_inside_each_glyphs_quad() {
    let Some(f) = fixture() else { return };
    let zones = Zones::of(&f.heros);
    for (code, e) in &f.table.glyphs {
        let (Choice::Heros, Some(p)) = (e.choice, e.placement) else { continue };
        let glyph = f.font.glyph(*code).unwrap();
        let [origin_x, _, left, right, ..] = glyph.metrics;
        let contours = place(&f.heros.glyphs[code], &zones, &f.table.models[p.run - 1], &p, f64::from(origin_x));
        let mut canvas = Canvas::new(32, 40);
        canvas.fill(&contours, |q| q);
        let coverage = canvas.coverage();
        for y in 0..40 {
            for x in 0..32 {
                let inside = x as i32 >= origin_x + left - 1 && (x as i32) < origin_x + right + 1;
                assert!(inside || coverage[y * 32 + x] < 0.02, "{code:04x}: ink {} at ({x}, {y}) outside its quad", coverage[y * 32 + x]);
            }
        }
    }
}

// Faithfulness at 1x: the chosen sources, drawn and averaged back to the console's pixels, are closer to them than today's
// bilinear magnification over the ASCII letters and over block 0; the Heros glyphs within 0.06 over ASCII.
#[test]
fn the_sharp_text_averages_back_closer_than_bilinear() {
    let Some(f) = fixture() else { return };
    let shapes = f.table.sharp_font(&f.font, &f.heros, &f.traced);
    let letters: Vec<i32> = (0x21..0x7f).filter(|c| matches!(f.table.glyphs[c].class, Some(Class::Letter | Class::Descender))).collect();
    let [sharp, traced, bilinear] = totals(&f.font, &shapes, &f.traced, &letters);
    eprintln!("ASCII letters: as drawn {:.4}, traced {:.4}, bilinear {:.4}", sharp.mean(), traced.mean(), bilinear.mean());
    assert!(sharp.mean() < bilinear.mean() && sharp.mean() <= 0.06);
    let all = block_zero_codes(&f.font);
    let [sharp, _, bilinear] = totals(&f.font, &shapes, &f.traced, &all);
    eprintln!("block 0: as drawn {:.4}, bilinear {:.4}", sharp.mean(), bilinear.mean());
    assert!(sharp.mean() < bilinear.mean());
}

fn cache_of(cells: Vec<i32>, cell_width: i32) -> GlyphCache {
    GlyphCache { address: 0xbc100, cell_width, cell_height: 44, width: 384, log_width: 9, log_height: 9, cells }
}

// The frame's cache and the layouts it passed through later (the Browser's) draw from one set of pictures: a code's cell holds
// the same texels in every atlas, and only its cell.
#[test]
fn every_layout_of_a_frame_gets_the_same_sharp_pictures() {
    let Some(f) = fixture() else { return };
    let shapes: SharpFont = f.table.sharp_font(&f.font, &f.heros, &f.traced);
    let k = 2u32;
    let mut pictures = Pictures::new(k);
    let mut first = SharpAtlas::new(k);
    let mut later = SharpAtlas::new(k);
    let word: Vec<i32> = "Browser@".chars().map(|c| c as i32).collect();
    first.update(&mut pictures, &f.font, &shapes, &cache_of(word.clone(), 40));
    let mut moved = vec![0; 20];
    moved[11..11 + word.len()].copy_from_slice(&word);
    later.update(&mut pictures, &f.font, &shapes, &cache_of(moved, 48));
    let cell = |atlas: &SharpAtlas, n: usize, width: u32| -> Vec<u8> {
        let columns = 384 / width as usize;
        let (x0, y0) = ((n % columns) as u32 * width * k, (n / columns) as u32 * 44 * k);
        let mut out = Vec::new();
        for y in y0..y0 + 42 * k {
            let at = ((y * atlas.width + x0) * 4) as usize;
            out.extend_from_slice(&atlas.rgba[at..at + (34 * k * 4) as usize]);
        }
        out
    };
    for (i, &code) in word.iter().enumerate() {
        let a = cell(&first, i, 40);
        assert_eq!(a, cell(&later, 11 + i, 48), "{code:04x}");
        assert!(a.chunks(4).any(|p| p[0] == 255), "{code:04x} has a white core");
    }
}
